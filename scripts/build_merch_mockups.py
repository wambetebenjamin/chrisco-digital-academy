def _font_cache_dir() -> str:
    d = os.path.join(tempfile.gettempdir(), "chrisco-merch-fonts")
    os.makedirs(d, exist_ok=True)
    return d


def _woff2_to_ttf(src: str, name: str, axes: dict | None = None) -> str:
    out = os.path.join(_font_cache_dir(), name + ".ttf")
    if os.path.exists(out):
        return out
    font = TTFont(src)
    if axes:
        instantiateVariableFont(font, axes, inplace=True)
    font.flavor = None
    font.save(out)
    return out


@lru_cache(maxsize=None)
def font(kind: str, size: int) -> ImageFont.FreeTypeFont:
    fm = os.path.join(ROOT, "node_modules", "@fontsource")
    fmvar = os.path.join(ROOT, "node_modules", "@fontsource-variable")
    if kind == "black":
        path = _woff2_to_ttf(os.path.join(fm, "archivo-black", "files", "archivo-black-latin-400-normal.woff2"), "archivo-black")
    elif kind == "cond":
        path = _woff2_to_ttf(os.path.join(fmvar, "archivo", "files", "archivo-latin-wdth-normal.woff2"), "archivo-cond", {"wdth": 78, "wght": 700})
    elif kind == "inter":
        path = _woff2_to_ttf(os.path.join(fmvar, "inter", "files", "inter-latin-wght-normal.woff2"), "inter-med", {"wght": 500})
    else:
        path = _woff2_to_ttf(os.path.join(fmvar, "archivo", "files", "archivo-latin-wdth-normal.woff2"), "archivo-bold", {"wdth": 100, "wght": 800})
    return ImageFont.truetype(path, size)


# --------------------------------------------------------------------------
# mask helpers
# --------------------------------------------------------------------------
def _blank() -> Image.Image:
    return Image.new("L", (W * SS, H * SS), 0)


def _rr(box, radius: int) -> Image.Image:
    m = _blank()
    ImageDraw.Draw(m).rounded_rectangle([c * SS for c in box], radius * SS, fill=255)
    return m


def _ell(box) -> Image.Image:
    m = _blank()
    ImageDraw.Draw(m).ellipse([c * SS for c in box], fill=255)
    return m


def _poly(points) -> Image.Image:
    m = _blank()
    ImageDraw.Draw(m).polygon([(x * SS, y * SS) for x, y in points], fill=255)
    return m


def _band(y0: int, y1: int) -> Image.Image:
    m = _blank()
    ImageDraw.Draw(m).rectangle([0, y0 * SS, W * SS, y1 * SS], fill=255)
    return m


def _rot_rect(cx, cy, w, h, radius, angle) -> Image.Image:
    piece = Image.new("L", (w * SS, h * SS), 0)
    ImageDraw.Draw(piece).rounded_rectangle([0, 0, w * SS - 1, h * SS - 1], radius * SS, fill=255)
    piece = piece.rotate(angle, expand=True, resample=Image.BICUBIC)
    m = _blank()
    m.paste(piece, (int(cx * SS - piece.width / 2), int(cy * SS - piece.height / 2)))
    return m


def _union(*masks) -> Image.Image:
    out = masks[0].copy()
    for m in masks[1:]:
        out = Image.composite(Image.new("L", out.size, 255), out, m)
    return out


def _inter(a: Image.Image, b: Image.Image) -> Image.Image:
    return Image.composite(a, Image.new("L", a.size, 0), b)


def _diff(a: Image.Image, b: Image.Image) -> Image.Image:
    return Image.composite(a, Image.new("L", a.size, 0), Image.eval(b, lambda v: 255 - v))


def _down(mask: Image.Image) -> Image.Image:
    return mask.resize((W, H), Image.LANCZOS)


def _f(mask: Image.Image, blur: float = 0.0) -> np.ndarray:
    """Downsample first, then blur at 1x: far cheaper and identical result."""
    down = _down(mask)
    if blur:
        down = down.filter(ImageFilter.GaussianBlur(blur))
    return np.asarray(down, dtype=np.float32) / 255.0


def _erode(mask: Image.Image, px: int) -> Image.Image:
    return mask.filter(ImageFilter.MinFilter(px * 2 + 1))


# --------------------------------------------------------------------------
# garments: smooth bezier silhouettes with soft fabric shading
# Each helper returns (mask, shade map, print box, ground shadow, details).
# Details are (name, mask, factor) regions painted over the base fabric:
# factors below 1 darken (collar ribs, interior shadows). Shapes are sampled
# cubic Beziers (never straight polygon cutouts) and all depth comes from
# blurred shade maps - no outline strokes, seam lines, hangers or rule bars.
# --------------------------------------------------------------------------
@lru_cache(maxsize=1)
def _shade_base() -> np.ndarray:
    y = np.linspace(0, 1, H, dtype=np.float32)[:, None]
    s = np.ones((H, W), np.float32) * (1.03 - 0.08 * y)
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
    r = np.sqrt(((xx - 600) / 620.0) ** 2 + ((yy - 470) / 660.0) ** 2)
    return s + 0.05 * np.clip(1 - r, 0, 1)


def _finish(mask, shade):
    """Common edge softening so light garments never look dirty."""
    shade = shade * (0.93 + 0.07 * _f(_erode(mask, 20), blur=40))
    return mask, shade


def _cubic(p0, p1, p2, p3, n=26):
    """Sample one cubic Bezier segment into dense points."""
    t = np.linspace(0, 1, n)[:, None]
    mt = 1 - t
    a, b, c, d = (np.array(p, np.float32) for p in (p0, p1, p2, p3))
    pts = mt**3 * a + 3 * mt**2 * t * b + 3 * mt * t**2 * c + t**3 * d
    return [(float(x), float(y)) for x, y in pts]


def _seg_path(start, segments):
    """Walk a mix of ('L', point) and ('C', c1, c2, end) segments."""
    pts = [tuple(start)]
    cur = tuple(start)
    for seg in segments:
        if seg[0] == "L":
            pts.append(tuple(seg[1]))
            cur = tuple(seg[1])
        else:
            _, c1, c2, end = seg
            pts.extend(_cubic(cur, c1, c2, end)[1:])
            cur = tuple(end)
    return pts


def _path_mask(pts) -> Image.Image:
    m = _blank()
    ImageDraw.Draw(m).polygon([(x * SS, y * SS) for x, y in pts], fill=255)
    return m


def _fold(cx, y0, y1, half_w, k, blur) -> np.ndarray:
    """One soft vertical fabric fold (darkener map)."""
    return k * _f(_ell((cx - half_w, y0, cx + half_w, y1)), blur)


