#!/usr/bin/env python3
"""
CHRISCO merchandise mockup renderer.

Every product mockup in public/merch is drawn here, deterministically, from
the supplied artwork in public/merch/source/. Nothing is traced by hand and
nothing is generated by an image model at render time.

Why programmatic: the brief for this range is "no lines anywhere". A renderer
owns every pixel, so garments carry soft shading instead of outline strokes,
seam stitches, hanger wires, drawstrings or rule bars, and every print is the
supplied artwork itself (or type set from the brand fonts) rather than an
interpretation of it.

Garment palette (one harmonious family: warm neutrals plus the brand ink):
  cocoa  #5A4232   cream #EFE6D4   ink #191A1C
  chalk  #F6F4EF   sand  #D8CCB2   teal #0E2A38

Usage:  .venv-merch/bin/python scripts/build_merch_mockups.py
Deps:   pillow, numpy, fonttools, brotli  (see scripts/merch-requirements.txt)
"""

