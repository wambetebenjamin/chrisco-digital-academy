def unwhite(img: Image.Image) -> Image.Image:
    """Drop the flat backdrop of an artwork and keep the ink as RGBA.

    The backdrop colour is sampled from the corners, then every pixel is
    keyed by its distance from that colour. Enclosed counters (inside O, R,
    A ...) sit at backdrop colour too, so they key out as well and letters
    keep their holes.
    """
    rgb = np.asarray(img.convert("RGB"), dtype=np.float32) / 255.0
    h, w = rgb.shape[:2]
    corners = np.concatenate([
        rgb[:10, :10].reshape(-1, 3), rgb[:10, -10:].reshape(-1, 3),
        rgb[-10:, :10].reshape(-1, 3), rgb[-10:, -10:].reshape(-1, 3)])
    bg = np.median(corners, axis=0)
    dist = np.sqrt(((rgb - bg) ** 2).sum(axis=2))
    alpha = np.clip((dist - 0.055) / 0.085, 0, 1)
    out = np.dstack([rgb, alpha[..., None]])
    art = Image.fromarray((out * 255).astype(np.uint8), "RGBA")
    return art.filter(ImageFilter.GaussianBlur(0.4))


def crop_art(img: Image.Image, pad: int = 6) -> Image.Image:
    a = np.asarray(img.split()[-1], dtype=np.uint8)
    ys, xs = np.where(a > 10)
    if len(xs) == 0:
        return img
    return img.crop((max(xs.min() - pad, 0), max(ys.min() - pad, 0),
                     min(xs.max() + pad, img.width), min(ys.max() + pad, img.height)))


def tighten(img: Image.Image, max_gap_ratio: float = 0.10) -> Image.Image:
    """Collapse oversized vertical whitespace between artwork rows.

    Every glyph and motif stays exactly as drawn; only the empty air between
    stacked rows is reduced, so a stray reference never floats far away.
    """
    a = np.asarray(img.split()[-1], dtype=np.uint8)
    rows = (a > 10).any(axis=1)
    if not rows.any():
        return img
    idx = np.where(rows)[0]
    top, bottom = idx[0], idx[-1] + 1
    height = bottom - top
    max_gap = max(6, int(height * max_gap_ratio))

    bands, start, gap = [], None, 0
    for y in range(top, bottom):
        if rows[y]:
            if start is None:
                start = y
            gap = 0
        elif start is not None:
            gap += 1
            if gap > max_gap:
                bands.append((start, y - gap + 1))
                start = None
    if start is not None:
        bands.append((start, bottom))
    if len(bands) < 2:
        return img

    pieces = [img.crop((0, b0, img.width, b1)) for b0, b1 in bands]
    gap_px = int(height * 0.05)
    out = Image.new("RGBA", (img.width, sum(p.height for p in pieces) + gap_px * (len(pieces) - 1)), (0, 0, 0, 0))
    y = 0
    for p in pieces:
        out.paste(p, (0, y), p)
        y += p.height + gap_px
    return out


def load_art(name: str) -> Image.Image:
    path = os.path.join(ART, name + ".png")
    if not os.path.exists(path):
        path = os.path.join(ART, "art", name + ".png")
    art = unwhite(Image.open(path).convert("RGB"))
    art = crop_art(art)
    art = tighten(art)
    return crop_art(art)


