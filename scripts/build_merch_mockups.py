# --------------------------------------------------------------------------
# composition
# --------------------------------------------------------------------------
@lru_cache(maxsize=1)
def background() -> np.ndarray:
    y = np.linspace(0, 1, H, dtype=np.float32)[:, None]
    top = np.array(BG_TOP, np.float32)
    bottom = np.array(BG_BOTTOM, np.float32)
    bg = top[None, :] * (1 - y[..., None]) + bottom[None, :] * y[..., None]
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
    r = np.sqrt(((xx - W / 2) / (W * 0.85)) ** 2 + ((yy - H / 2) / (H * 0.85)) ** 2)
    return bg * (1 - 0.05 * np.clip(r, 0, 1) ** 2)[..., None]


def chest_warp(art: Image.Image, k: float = 0.03) -> Image.Image:
    """Mild cylindrical bulge so a chest print follows the garment instead
    of reading as a pasted flat rectangle: middle rows run widest, top and
    bottom rows tuck in, like fabric wrapping a torso. Inverse-mapped with
    bilinear sampling so no holes or seams appear."""
    src = np.asarray(art.convert("RGBA"), dtype=np.float32)
    h, w = src.shape[:2]
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    v = yy / max(h - 1, 1)
    u = (xx - w * 0.5) / (w * (1.0 + 4.0 * k * (v - 0.5) ** 2)) + 0.5

    x0 = np.floor(u * (w - 1)).astype(np.int32)
    y0 = np.floor(v * (h - 1)).astype(np.int32)
    x1 = np.clip(x0 + 1, 0, w - 1)
    y1 = np.clip(y0 + 1, 0, h - 1)
    x0 = np.clip(x0, 0, w - 1)
    y0 = np.clip(y0, 0, h - 1)
    fx = (u * (w - 1) - x0)[..., None]
    fy = (v * (h - 1) - y0)[..., None]

    top = src[y0, x0] * (1 - fx) + src[y0, x1] * fx
    bot = src[y1, x0] * (1 - fx) + src[y1, x1] * fx
    out = top * (1 - fy) + bot * fy
    outside = (u < 0) | (u > 1)
    out[outside] = 0
    return Image.fromarray(np.clip(out, 0, 255).astype(np.uint8), "RGBA")


def render(garment: str, colour: str, art: Image.Image | None, out_name: str,
           print_scale: float = 1.0) -> None:
    mask, shade, (pcx, pcy, pw, ph), ground, details = GARMENTS[garment]()
    mask_f = _f(mask, blur=1.0)
    rgb = np.clip(np.array(PALETTE[colour], np.float32)[None, None, :] * shade[..., None], 0, 255)

    canvas = background()
    canvas *= (1 - (_f(_ell(ground), blur=60) * 0.09)[..., None])
    canvas = canvas * (1 - mask_f[..., None]) + rgb * mask_f[..., None]

    # Collar ribs, neck interiors, hood rings and similar depth details are
    # painted as darkened fabric rather than cut through to the backdrop.
    for _name, detail_mask, factor in details:
        df = _f(detail_mask, blur=1.6)
        canvas = canvas * (1 - df[..., None]) + canvas * factor * df[..., None]

    if art is not None:
        ratio = min((pw * print_scale) / art.width, (ph * print_scale) / art.height)
        nw, nh = max(2, int(art.width * ratio)), max(2, int(art.height * ratio))
        piece = art.resize((nw, nh), Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.5))
        if garment in ("tee", "hoodie", "polo"):
            piece = chest_warp(piece)
        px0, py0 = pcx - nw // 2, pcy - nh // 2
        arr = np.asarray(piece, np.float32) / 255.0
        a = arr[..., 3:4] * mask_f[py0:py0 + nh, px0:px0 + nw][..., None]
        local = shade[py0:py0 + nh, px0:px0 + nw][..., None]
        ink = arr[..., :3] * 255.0 * (0.62 + 0.38 * local)
        region = canvas[py0:py0 + nh, px0:px0 + nw]
        canvas[py0:py0 + nh, px0:px0 + nw] = region * (1 - a) + ink * a

    canvas += np.random.default_rng(7).uniform(-1.1, 1.1, canvas.shape).astype(np.float32)
    Image.fromarray(np.clip(canvas, 0, 255).astype(np.uint8), "RGB").save(os.path.join(OUT, out_name), compress_level=6)
    print("rendered", out_name)


